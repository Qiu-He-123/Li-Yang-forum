# 允许的代码长度放宽到 12，覆盖 [让我看看]、[社会社会] 等长代码
_EMOJI_CODE_RE = re.compile(r"\[[^\[\]]{1,12}\]")


def convert_wechat_emoji(text: str | None) -> str:
    """把文本里的微信表情代码 [xx] 替换成真实 Emoji；未收录的代码原样保留。"""
    if not text:
        return text or ""

    def _replace(match: re.Match[str]) -> str:
        return WECHAT_EMOJI_MAP.get(match.group(0), match.group(0))

    return _EMOJI_CODE_RE.sub(_replace, text)
